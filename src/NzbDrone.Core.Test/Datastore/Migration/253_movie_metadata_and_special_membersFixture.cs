using Dapper;
using FluentAssertions;
using FluentMigrator;
using NUnit.Framework;
using NzbDrone.Core.Datastore.Migration;
using NzbDrone.Core.Test.Framework;

namespace NzbDrone.Core.Test.Datastore.Migration
{
    [TestFixture]
    public class MovieMetadataMigrationFixture : MigrationTest<movie_metadata_and_special_members>
    {
        [Test]
        public void should_backfill_only_verified_native_anime_features_and_preserve_manual_tv_movie_roles()
        {
            using var db = WithDapperMigrationTestDb(migration =>
            {
                // PostgreSQL identities reject explicit fixture IDs by default.
                migration.IfDatabase(ProcessorIdConstants.PostgreSQL).Execute.Sql("ALTER TABLE \"Series\" ALTER COLUMN \"Id\" SET GENERATED BY DEFAULT; ALTER TABLE \"Episodes\" ALTER COLUMN \"Id\" SET GENERATED BY DEFAULT;");
                foreach (var id in new[] { 1, 2, 3, 4, 5 })
                {
                    migration.Insert.IntoTable("Series").Row(new
                    {
                        Id = id, TvdbId = -id, TvRageId = 0, TvMazeId = 0, Title = "Native entry " + id, CleanTitle = "nativeentry" + id,
                        Status = 0, Images = "[]", Path = "/generated/Original/Feature " + id, Monitored = true, SeasonFolder = true,
                        Runtime = 95, SeriesType = 0, UseSceneNumbering = false, TitleSlug = "native-entry-" + id, Seasons = "[{\"seasonNumber\":1}]",
                        Genres = "[]", Tags = "[]", Actors = "[]", QualityProfileId = 1, OriginalLanguage = 1,
                        Added = "2020-01-01 00:00:00", MetadataSource = id == 3 ? 0 : id == 4 ? 3 : 2, ForeignId = (970000 + id).ToString(),
                        AnimeGroupingMode = 1, AnimeGroupId = "manual:original", AnimeGroupTitle = "Original",
                        AnimeGroupMemberKind = 1, AnimeGroupMovieNumber = id, AnimeGroupFolder = "Original"
                    });
                    migration.Insert.IntoTable("Episodes").Row(new
                    {
                        Id = id, SeriesId = id, SeasonNumber = id == 5 ? 0 : 1, EpisodeNumber = 1, Title = "Native feature " + id,
                        Monitored = true, EpisodeFileId = 100 + id, ForeignId = "native-" + id, UnverifiedSceneNumbering = false, Runtime = 0, Watched = false
                    });
                }

                migration.Insert.IntoTable("Episodes").Row(new
                {
                    Id = 20, SeriesId = 2, SeasonNumber = 1, EpisodeNumber = 2, Title = "Second native TV episode",
                    Monitored = false, EpisodeFileId = 0, ForeignId = "native-20", UnverifiedSceneNumbering = false, Runtime = 0, Watched = false
                });
                migration.IfDatabase(ProcessorIdConstants.PostgreSQL).Execute.Sql("ALTER TABLE \"Series\" ALTER COLUMN \"Id\" SET GENERATED ALWAYS; ALTER TABLE \"Episodes\" ALTER COLUMN \"Id\" SET GENERATED ALWAYS;");
            });

            foreach (var id in new[] { 1, 2, 3, 4, 5 })
            {
                db.QuerySingle<int>("SELECT \"MediaType\" FROM \"Series\" WHERE \"Id\"=@id", new { id }).Should().Be(id is 1 or 4 ? 1 : 0);
                db.QuerySingle<int>("SELECT \"AnimeGroupMovieNumber\" FROM \"Series\" WHERE \"Id\"=@id", new { id }).Should().Be(id);
                db.QuerySingle<string>("SELECT \"ForeignId\" FROM \"Episodes\" WHERE \"Id\"=@id", new { id }).Should().Be("native-" + id);
                db.QuerySingle<int>("SELECT \"EpisodeFileId\" FROM \"Episodes\" WHERE \"Id\"=@id", new { id }).Should().Be(100 + id);
            }

            db.QuerySingle<int>("SELECT COUNT(*) FROM \"Episodes\"").Should().Be(6);
            db.QuerySingle<bool>("SELECT \"Monitored\" FROM \"Episodes\" WHERE \"Id\"=20").Should().BeFalse();
            MigrationVersion.Should().Be(253);
        }
    }
}
